    /**
     * Creates and starts the timer for the smooth scrolling text effect.
     */
    private void startMarquee() {
        javax.swing.Timer timer = new javax.swing.Timer(15, new java.awt.event.ActionListener() {
            @Override
            public void actionPerformed(java.awt.event.ActionEvent e) {
                marqueeX -= 3; 
                
                if (marqueeX < -1000) {
                    marqueeX = jPanel1.getWidth(); 
                }
                
                jLabelCOLLEGE_NAME.setLocation(marqueeX, jLabelCOLLEGE_NAME.getY());
            }
        });
        timer.start();
    }
    
    /**
     * A helper method to safely load images without crashing the app.
     */
    private void setSafeImage(javax.swing.JLabel label, String imagePath, String fallbackText) {
        java.net.URL imgUrl = getClass().getResource(imagePath);
        if (imgUrl != null) {
            label.setIcon(new javax.swing.ImageIcon(imgUrl));
            label.setText(""); 
        } else {
            System.err.println("Warning: Could not find image at " + imagePath);
            label.setText(fallbackText); 
        }
    }
