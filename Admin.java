    private void jButton_SUBMIT_ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_SUBMIT_ActionPerformed
    String enteredId = jTextField_USER_ID.getText().trim(); 
        String enteredPass = new String(jPasswordField_PASSWORD.getPassword());     

        if (enteredId.isEmpty() || enteredPass.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter both User ID and Password.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (enteredId.equals("@Admin") && enteredPass.equals("Admin")) {
            JOptionPane.showMessageDialog(this, "Admin Login Successful!", "Welcome", JOptionPane.INFORMATION_MESSAGE);
            this.dispose(); 
            
            // SUCCESSFULLY ROUTES TO THE NEW ADMIN DATA PAGE
            new Admin_Can_show_Data().setVisible(true); 
        } else {
            JOptionPane.showMessageDialog(this, "Invalid Credentials! Only Admins can access this portal.", "Access Denied", JOptionPane.ERROR_MESSAGE);
            jPasswordField_PASSWORD.setText(""); 
        }                                         // Returns safely to the landing page                                
    }//GEN-LAST:event_jButton_SUBMIT_ActionPerformed

