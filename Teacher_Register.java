    private void jButton_REGISTER_ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_REGISTER_ActionPerformed
    String fn = jTextField_INPUT_FIRST_NAME_.getText().trim();
        String mn = jTextField_INPUT_MIDDLE_NAME_.getText().trim();
        String ln = jTextField_INPUT_LAST_NAME_.getText().trim();
        String dob = jTextField_INPUT_DATE_OF_BIRTH_.getText().trim();
        String uid = jTextField_INPUT_USER_ID_.getText().trim();
        String pass = jTextField_INPUT_PASSWORD_.getText();
        String repass = jTextField_INPUT_RETYPE_PASSWORD_.getText();
        String mobile = jTextField_INPUT_MOBILE_.getText().trim();
        String email = jTextField_INPUT_EMAIL_.getText().trim();
        String dept = (String) jComboBox1.getSelectedItem(); // Reads from JComboBox
        String address = jTextArea_INPUT_ADDRESS_.getText().trim();

        // Basic Validations
        if (uid.isEmpty() || pass.isEmpty() || fn.isEmpty()) {
            JOptionPane.showMessageDialog(this, "First Name, User ID, and Password are required fields.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (!pass.equals(repass)) {
            JOptionPane.showMessageDialog(this, "Passwords do not match!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Updated SQL Query matching the new database schema with 11 parameters
        String query = "INSERT INTO teachers (user_id, first_name, middle_name, last_name, dob, email, password, mobile, department, address, register_time) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)";

        try (Connection conn = DriverManager.getConnection(URL, USER, PASSWORD);
             PreparedStatement pstmt = conn.prepareStatement(query)) {
            
            pstmt.setString(1, uid);
            pstmt.setString(2, fn);
            pstmt.setString(3, mn.isEmpty() ? null : mn); // Stores middle name cleanly
            pstmt.setString(4, ln);
            pstmt.setString(5, dob.isEmpty() ? null : dob); // Sends null if empty instead of crashing
            pstmt.setString(6, email);
            pstmt.setString(7, pass);
            pstmt.setString(8, mobile);
            pstmt.setString(9, dept);
            pstmt.setString(10, address);
            pstmt.setTimestamp(11, new Timestamp(System.currentTimeMillis())); // Automatic Timestamp
            
            int rowsInserted = pstmt.executeUpdate();
            if (rowsInserted > 0) {
                JOptionPane.showMessageDialog(this, "Teacher Registered Successfully!\nYour User ID is: " + uid, "Success", JOptionPane.INFORMATION_MESSAGE);
                
                // Clear the fields
                jButton_CLEAR_ActionPerformed(null);
                
                // Route back to Login Page
                this.dispose();
                new Visit().setVisible(true);
            }
            
        } catch (SQLException ex) {
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            
            // Check for Duplicate User ID (MySQL Error 1062)
            if (ex.getErrorCode() == 1062) {
                JOptionPane.showMessageDialog(this, "That UserID is already taken. Please choose another.", "Registration Error", JOptionPane.ERROR_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButton_REGISTER_ActionPerformed

