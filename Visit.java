    private void jButton_SUBMIT_ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_SUBMIT_ActionPerformed
        String uid = jTextField_INPUT_UID_.getText().trim();
        String pass = new String(jPasswordField_INPUT_PASS_.getPassword());

        if (uid.isEmpty() || pass.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter both User ID and Password.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String query = "SELECT * FROM teachers WHERE user_id = ? AND password = ?";

        try (Connection conn = DriverManager.getConnection(URL, USER, PASSWORD);
             PreparedStatement pstmt = conn.prepareStatement(query)) {

            pstmt.setString(1, uid);
            pstmt.setString(2, pass);

            try (ResultSet rs = pstmt.executeQuery()) {
                if (rs.next()) {
                    String firstName = rs.getString("first_name");
                    JOptionPane.showMessageDialog(this, "Welcome Teacher " + firstName + "!\nLogin Successful. Opening Student Registration...");
                    
                    // CLOSES LOGIN AND OPENS REGISTRATION WITH TEACHER ID!
                    this.dispose(); 
                    new Student_Register(uid).setVisible(true);
                    
                } else {
                    JOptionPane.showMessageDialog(this, "Invalid User ID or Password.", "Login Failed", JOptionPane.ERROR_MESSAGE);
                }
            }
        } catch (SQLException ex) {
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton_SUBMIT_ActionPerformed

