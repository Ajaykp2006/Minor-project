    private void jButton_REGISTER_ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_REGISTER_ActionPerformed
        String fn = jTextField_INPUT_FN_.getText().trim();
        String mn = jTextField_Middle_name_.getText().trim();
        String ln = jTextField_INPUT_LN.getText().trim();
        String dob = jTextField_INPUT_DOB_.getText().trim();
        String uid = jTextField_INPUT_UID_.getText().trim();
        String pass = jTextField_INPUT_PASS_.getText();
        String repass = jTextField_Re_Pass_.getText();
        String mobile = jTextField_INPUT_MOBILE_NO_.getText().trim();
        String email = jTextField_INPUT_EID_.getText().trim();
        String course = (String) jComboBox1.getSelectedItem(); // Reads from JComboBox
        String address = jTextArea_INPUT_ADD_.getText().trim();

        // Basic Validations
        if (uid.isEmpty() || pass.isEmpty() || fn.isEmpty()) {
            JOptionPane.showMessageDialog(this, "First Name, User ID, and Password are required fields.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (!pass.equals(repass)) {
            JOptionPane.showMessageDialog(this, "Passwords do not match!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // SQL Query matching the 'students' table and enforcing the session tracking (registered_by)
        String query = "INSERT INTO students (user_id, first_name, middle_name, last_name, dob, email, password, mobile, department, address, register_time, registered_by) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)";

        try (Connection conn = DriverManager.getConnection(URL, USER, PASSWORD);
             PreparedStatement pstmt = conn.prepareStatement(query)) {
            
            pstmt.setString(1, uid);
            pstmt.setString(2, fn);
            pstmt.setString(3, mn.isEmpty() ? null : mn);
            pstmt.setString(4, ln);
            pstmt.setString(5, dob.isEmpty() ? null : dob); // Sends null if empty instead of crashing
            pstmt.setString(6, email);
            pstmt.setString(7, pass);
            pstmt.setString(8, mobile);
            pstmt.setString(9, course);
            pstmt.setString(10, address);
            pstmt.setTimestamp(11, new Timestamp(System.currentTimeMillis())); // Automatic Timestamp
            
            // This is the crucial link: It assigns the active teacher's ID to this student
            pstmt.setString(12, loggedInTeacherId); 
            
            int rowsInserted = pstmt.executeUpdate();
            if (rowsInserted > 0) {
                JOptionPane.showMessageDialog(this, "Student Registered Successfully by Teacher: " + loggedInTeacherId + "\nStudent User ID is: " + uid, "Registration Success", JOptionPane.INFORMATION_MESSAGE);
                
                // Clear the fields for the next student registration
                jButton_CANCEL_ActionPerformed(null);
            }
            
        } catch (SQLException ex) {
            logger.log(java.util.logging.Level.SEVERE, null, ex);
            
            // Check for Duplicate User ID (MySQL Error 1062)
            if (ex.getErrorCode() == 1062) {
                JOptionPane.showMessageDialog(this, "That Student User ID is already taken. Please choose another.", "Registration Error", JOptionPane.ERROR_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButton_REGISTER_ActionPerformed

